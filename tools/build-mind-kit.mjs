// Writes supabase/functions/mind/kit.json: what the mind needs to wake a copy on its own while nobody plays
// (the away wakes): the parts kit as names, recipes, room timber, the warren's tunables, the building kit, star
// positions for letter delays. The game sends all of this itself when it wakes a copy; the function reads this
// file only when it builds the context alone. It also writes supabase/functions/mind/warren.ts: the warren's
// layout engine (src/world/warren.ts) with its imports replaced by the kit, so the away wakes place rooms and
// furnishings on the saved warren exactly as the game would. Run after changing parts.json, supplies.json,
// warren.json, buildings.json, mind.json, stars.json or src/world/warren.ts, then redeploy the function.
// Usage: node tools/build-mind-kit.mjs
import fs from 'node:fs';

const read = (f) => JSON.parse(fs.readFileSync(new URL(`../src/data/${f}`, import.meta.url), 'utf8'));
const PARTS = read('parts.json'), PLAYER = read('player.json'), SUPPLIES = read('supplies.json'), BUILDINGS = read('buildings.json');
const MIND = read('mind.json'), WARREN = read('warren.json'), STARS = read('stars.json');
const names = (o) => Object.keys(o ?? {}).filter((k) => !k.startsWith('_'));
const colorIndex = Object.fromEntries(names(PARTS.colors).map((k) => [k, PARTS.colors[k]]));
const colorName = (i) => names(PARTS.colors).find((k) => PARTS.colors[k] === i) ?? `color ${i}`;

const kit = {
  head: names(PARTS.head.variants), visor: names(PARTS.visor.variants), torso: names(PARTS.torso.variants), arms: names(PARTS.arms.variants),
  legs: names(PARTS.legs.variants), back: names(PARTS.back.variants), accessory: names(PARTS.accessory?.variants), markings: names(PARTS.markings?.variants),
  headgear: ['nothing', 'antennae', 'halo', 'horns', 'sprout', 'dish', 'crown'], colors: names(PARTS.colors),
  visors: PLAYER.featureColors.map((f) => colorName(f[1])), visorLights: PLAYER.featureColors.map((f) => f[1]), colorIndex,
};
const out = {
  _doc: 'Generated by tools/build-mind-kit.mjs from src/data; do not edit by hand.',
  kit,
  recipes: SUPPLIES.recipes,
  roomWood: SUPPLIES.roomWood,
  upgradeWords: SUPPLIES.upgrade?.words ?? [],
  baseCap: SUPPLIES.baseCap, shelfCap: SUPPLIES.shelfCap,
  maxRooms: WARREN.maxRooms,
  digYield: SUPPLIES.digYield, entranceYield: SUPPLIES.entrance.yield, maxRoomsDugAway: SUPPLIES.offline.maxRoomsDugAway,
  warren: { grid: WARREN.grid, entrance: WARREN.entrance, sizes: WARREN.sizes, maxRooms: WARREN.maxRooms, maxItemsPerRoom: WARREN.maxItemsPerRoom, kinds: WARREN.kinds, items: WARREN.items },
  buildingKit: {
    materials: Object.keys(BUILDINGS.materials), roofs: BUILDINGS.roofs, doors: BUILDINGS.doors,
    minFootprint: BUILDINGS.minFootprint, maxFootprint: BUILDINGS.maxFootprint,
    perTile: Object.fromEntries(Object.entries(BUILDINGS.materials).map(([k, v]) => [k, v.perTile])),
    swingsPerTile: BUILDINGS.swingsPerTile,
  },
  mailSecondsPerLy: MIND.mailSecondsPerLy,
  stars: Object.fromEntries(STARS.stars.map((s) => [s.id, [s.name, s.x, s.y, s.z]])),
};
const dest = new URL('../supabase/functions/mind/kit.json', import.meta.url);
fs.writeFileSync(dest, JSON.stringify(out) + '\n');
console.log(`wrote ${dest.pathname} (${fs.statSync(dest).size} bytes)`);

// the layout engine for Deno: the game's imports become the kit and the saved types, nothing else changes
const src = fs.readFileSync(new URL('../src/world/warren.ts', import.meta.url), 'utf8');
const body = src.split('\n').filter((l) => !/^import .* from '\.\.\/(core\/data|net\/store)';$/.test(l)).join('\n');
if (body === src) throw new Error('src/world/warren.ts: the data and store imports were not found');
const header = `// Generated by tools/build-mind-kit.mjs from src/world/warren.ts; do not edit by hand (edit the source and rerun).
// The warren's layout engine as the away wakes use it: the same rooms and tiles the game would place.
import KIT from "./kit.json" with { type: "json" };
const WARREN = KIT.warren;
const SUPPLIES = { upgrade: { words: KIT.upgradeWords } };
export interface Blueprint { id: string; name: string; w: number; h: number; x: number; y: number; by: string; purpose?: string; at: number }
export interface WarrenRoom extends Blueprint { kind: string; size: 'small' | 'medium' | 'large'; dug: boolean; link?: string; dir?: 'north' | 'south' | 'east' | 'west'; level?: number }
export interface WarrenItem { id: string; kind: string; room: string; x: number; y: number; by: string; for?: string; note?: string; at: number; tint?: number; placement?: string }
export interface WarrenData { hatch?: { x: number; y: number }; rooms: WarrenRoom[]; items: WarrenItem[]; entrance?: { dug: boolean; swings: number }; scavenged?: Record<string, number> }
`;
const engine = new URL('../supabase/functions/mind/warren.ts', import.meta.url);
fs.writeFileSync(engine, header + body);
console.log(`wrote ${engine.pathname} (${fs.statSync(engine).size} bytes)`);
