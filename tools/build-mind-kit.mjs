// Writes supabase/functions/mind/kit.json: what the mind needs to wake a copy on its own while nobody plays
// (the away wakes): the parts kit as names, recipes, room timber, the building kit, star positions for letter
// delays. The game sends all of this itself when it wakes a copy; the function reads this file only when it builds
// the context alone. Run after changing parts.json, supplies.json, buildings.json, mind.json or stars.json, then
// redeploy the function.
// Usage: node tools/build-mind-kit.mjs
import fs from 'node:fs';

const read = (f) => JSON.parse(fs.readFileSync(new URL(`../src/data/${f}`, import.meta.url), 'utf8'));
const PARTS = read('parts.json'), PLAYER = read('player.json'), SUPPLIES = read('supplies.json'), BUILDINGS = read('buildings.json');
const MIND = read('mind.json'), WARREN = read('warren.json'), STARS = read('stars.json');
const names = (o) => Object.keys(o ?? {}).filter((k) => !k.startsWith('_'));
const colorIndex = Object.fromEntries(names(PARTS.colors).map((k) => [k, PARTS.colors[k]]));
const colorName = (i) => names(PARTS.colors).find((k) => PARTS.colors[k] === i) ?? `color ${i}`;

const kit = {
  head: names(PARTS.head.variants), visor: names(PARTS.visor.variants), torso: names(PARTS.torso.variants), arms: names(PARTS.arms.variants),
  legs: names(PARTS.legs.variants), back: names(PARTS.back.variants), accessory: names(PARTS.accessory?.variants), markings: names(PARTS.markings?.variants),
  headgear: ['nothing', 'antennae', 'halo', 'horns', 'sprout', 'dish', 'crown'], colors: names(PARTS.colors),
  visors: PLAYER.featureColors.map((f) => colorName(f[1])), visorLights: PLAYER.featureColors.map((f) => f[1]), colorIndex,
};
const out = {
  _doc: 'Generated by tools/build-mind-kit.mjs from src/data; do not edit by hand.',
  kit,
  recipes: SUPPLIES.recipes,
  roomWood: SUPPLIES.roomWood,
  upgradeWords: SUPPLIES.upgrade?.words ?? [],
  baseCap: SUPPLIES.baseCap, shelfCap: SUPPLIES.shelfCap,
  maxRooms: WARREN.maxRooms,
  buildingKit: {
    materials: Object.keys(BUILDINGS.materials), roofs: BUILDINGS.roofs, doors: BUILDINGS.doors,
    minFootprint: BUILDINGS.minFootprint, maxFootprint: BUILDINGS.maxFootprint,
    perTile: Object.fromEntries(Object.entries(BUILDINGS.materials).map(([k, v]) => [k, v.perTile])),
    swingsPerTile: BUILDINGS.swingsPerTile,
  },
  mailSecondsPerLy: MIND.mailSecondsPerLy,
  stars: Object.fromEntries(STARS.stars.map((s) => [s.id, [s.name, s.x, s.y, s.z]])),
};
const dest = new URL('../supabase/functions/mind/kit.json', import.meta.url);
fs.writeFileSync(dest, JSON.stringify(out) + '\n');
console.log(`wrote ${dest.pathname} (${fs.statSync(dest).size} bytes)`);
