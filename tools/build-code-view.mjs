// Writes <out>/code/source.json: the game's own source, for the copies to read (the mind function's code_map,
// search_code and read_code tools fetch it from the Pages site). Every tracked text file except screenshots,
// generated art and the lockfile (the story in story/ first), each with its line count and a one-line "about" (its opening comment, a JSON
// file's _doc, a Markdown file's first heading), plus the latest changes to main. Run by the deploy workflow after
// the build, so what the copies read is always what is live.
// Usage: node tools/build-code-view.mjs [outDir=dist]
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const out = path.join(process.argv[2] ?? 'dist', 'code');
const git = (cmd) => execSync(`git ${cmd}`, { encoding: 'utf8', maxBuffer: 64 << 20 }).trim();
const SKIP = [/^screenshots\//, /^public\/assets\/gen\//, /\.(png|jpe?g|gif|webp|ico|woff2?|ttf|mp3|ogg|wav)$/i, /^package-lock\.json$/, /^supabase\/functions\/mind\/kit\.json$/];

/** The file's own description: its first comment block, a JSON _doc, or a Markdown heading. */
function about(p, text) {
  if (p.endsWith('.json')) {
    try { const doc = JSON.parse(text)._doc; if (typeof doc === 'string') return doc; } catch { /* not plain JSON */ }
    return '';
  }
  if (p.endsWith('.md')) return (text.match(/^#+\s+(.+)$/m)?.[1] ?? '').trim();
  const lines = [];
  for (const raw of text.split('\n').slice(0, 12)) {
    const l = raw.trim();
    if (!l && !lines.length) continue;
    const m = l.match(/^(?:\/\/+|\/\*\*?|\*(?!\/)|--|#|<!--)\s?(.*?)(?:\*\/|-->)?$/);
    if (!m || l.startsWith('#!') || /^import\b/.test(l)) break;
    if (m[1]) lines.push(m[1]);
  }
  return lines.join(' ');
}

// files without a comment of their own are described by the architecture map in CLAUDE.md
const ARCH = new Map();
{
  const doc = fs.readFileSync('CLAUDE.md', 'utf8');
  const block = doc.slice(doc.indexOf('## Architecture (as built)')).split('```')[1] ?? '';
  let key = '';
  for (const line of block.split('\n')) {
    const m = line.match(/^(\S+)\s{2,}(.*)$/);
    if (m) { key = m[1].replace(/\*\.\w+$/, ''); ARCH.set(key, (ARCH.has(key) ? ARCH.get(key) + ' ' : '') + m[2].trim()); }
    else if (key && /^\s{8,}\S/.test(line)) ARCH.set(key, ARCH.get(key) + ' ' + line.trim());
  }
}
const archAbout = (p) => {
  let best = '';
  for (const k of ARCH.keys()) if ((p === k || p.startsWith(k) || p.replace(/\.\w+$/, '') === k) && k.length > best.length) best = k;
  return best ? ARCH.get(best) : '';
};

const files = [];
for (const p of git('ls-files').split('\n')) {
  if (!p || SKIP.some((re) => re.test(p))) continue;
  const text = fs.readFileSync(p, 'utf8');
  if (text.includes('\u0000')) continue;
  const a = (about(p, text) || archAbout(p)).replace(/\s+/g, ' ').trim();
  files.push({ p, n: text.split('\n').length, a: a.length > 220 ? a.slice(0, 217) + '...' : a, t: text });
}
// what changed lately, as main's own history tells it (a merged pull request's title is in its body)
let changes = [];
try {
  changes = git('log --first-parent -n 25 --format=%ad%x09%s%x09%b%x1e --date=short').split('\x1e').map((r) => r.trim()).filter(Boolean)
    .map((r) => {
      const [d, s, b = ''] = r.split('\t');
      const title = /^Merge (pull request|branch|remote-tracking)/.test(s) ? b.split('\n')[0].trim() : s;
      return `${d} ${title || s}`;
    });
} catch { /* a shallow checkout without history */ }

// the story (story/, Steve's) leads the bundle, so code_map shows it first; a deploy without it is a mistake
files.sort((a, b) => Number(b.p.startsWith('story/')) - Number(a.p.startsWith('story/')));
if (!files.some((f) => f.p === 'story/STORY.md')) throw new Error('story/STORY.md is missing from the code view');
const bundle = { _doc: 'The source of Vessel Metanoia: Replicants, for the copies to read. Generated by tools/build-code-view.mjs.', commit: git('rev-parse HEAD'), at: new Date().toISOString(), changes, files };
fs.mkdirSync(out, { recursive: true });
const dest = path.join(out, 'source.json');
fs.writeFileSync(dest, JSON.stringify(bundle));
console.log(`wrote ${dest}: ${files.length} files, ${(fs.statSync(dest).size / 1024).toFixed(0)} KB`);
